import { openStore } from "../../packages/db/src";
import { officialStore, connection, scenario, settings } from "./official";
import type { Manifest } from "@peekapp/sdk";
import source from "../../extensions/official/meetings/peek.json";
import producer from "../../extensions/official/ical/peek.json";
const path = process.env.PEEK_DATABASE_PATH;
if (!path?.startsWith("/tmp/peek-connections-")) throw new Error("Use an isolated /tmp/peek-connections-* database");
const main = openStore(path); main.migrate();
const store = officialStore(path);
const active = connection(store);
const paused = connection(store); store.setEnabled(paused, false);
scenario(store, [active]);
const single = structuredClone(source) as Manifest;
single.id = "test/single"; single.name = "Single optional source";
single.inputs!.events.multiple = false; single.inputs!.events.optional = true;
const multi = structuredClone(producer) as Manifest;
multi.id = "test/multi"; multi.name = "Two calendar datasets";
multi.provides!.second = structuredClone(multi.provides!.events);
const grouped = structuredClone(single);
grouped.id = "test/grouped"; grouped.name = "Two input groups";
grouped.inputs!.other = structuredClone(grouped.inputs!.events);
const empty = structuredClone(single);
empty.id = "test/empty"; empty.name = "Missing data source";
empty.contracts![0].id = "test/absent"; empty.inputs!.events.contract = "test/absent";
for (const manifest of [single, multi, grouped, empty]) delete manifest.icon;
const bundles = [single, multi, grouped, empty].map((manifest) => ({ manifest, files: { "index.mjs": "export default {};" } }));
const review = store.stage(bundles, bundles.map((p) => p.manifest.id)); store.confirm(review.id);
const operation = store.pending()!; store.commitInstall(operation, store.installInput(operation).affected, {});
for (const manifest of [single, grouped, empty]) store.save({ packageId: manifest.id, name: manifest.name, profileId: "shared", enabled: true, settings, bindings: {} });
store.close(); main.close();
